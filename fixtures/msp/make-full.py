#!/usr/bin/env python3
"""Generate `synthetic-full.jsonl`: one transcript with every shape on it.

The populated captures (docs/82 1.5, entry `transcript-full`) need one
session that shows markdown with a heading, a list, code and a table; every
tool card shape (shell, read, todo, JSON result, a folded tool group, a
diff with its stat line); a plan with its todo list; and, last, an
approval and a question both still waiting on the person.

Nothing here is new evidence. Each part is copied from a hand-written
`synthetic-*` fixture or a sanitised `transcript-*` capture already in this
folder; only their notifications are kept (no requests, no replies), and
they are re-keyed onto one session id with unique turn and item ids and one
running `viewCursor`.

The `synthetic-` prefix is load-bearing: this file was never on a wire.

Sends and costs: nothing. It reads files in this folder and writes one.

    python3 fixtures/msp/make-full.py --out fixtures/msp/synthetic-full.jsonl
"""
import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SID = "synthetic-full"

# (file, tag, stop_after_method): parts in transcript order. A stop method
# ends that part after its first occurrence — the question is left pending.
PARTS = [
    ("synthetic-markdown.jsonl", "md", None),
    ("synthetic-toolshapes.jsonl", "ts", None),
    ("synthetic-toolgroup.jsonl", "tg", None),
    ("synthetic-diffstat.jsonl", "df", None),
    ("synthetic-todo-goal.jsonl", "pl", None),
    ("transcript-approve.jsonl", "ap", "approval/requested"),
    ("synthetic-userinput-clarify.jsonl", "q", "userInput/requested"),
]

# Fields whose values are ids local to one source file.
ID_KEYS = {"turnId", "itemId", "callId", "approvalId", "requestId", "activeTurnId", "parentItemId"}


def frames(path):
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line.startswith("<-- "):
                continue
            msg = json.loads(line[4:])
            if "method" in msg:
                yield msg


def rekey(value, tag, source_sid):
    if isinstance(value, dict):
        out = {}
        for key, inner in value.items():
            if key == "sessionId" and inner == source_sid:
                out[key] = SID
            elif key in ID_KEYS and isinstance(inner, str):
                out[key] = f"{tag}-{inner}"
            else:
                out[key] = rekey(inner, tag, source_sid)
        return out
    if isinstance(value, list):
        return [rekey(inner, tag, source_sid) for inner in value]
    return value


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    out, cursor, started = [], 0, False
    for name, tag, stop in PARTS:
        source_sid = None
        for msg in frames(os.path.join(HERE, name)):
            params = msg.get("params") or {}
            if msg["method"] == "session/started":
                source_sid = params["session"]["sessionId"]
                if started:
                    continue
                started = True
                params["session"]["sessionId"] = SID
                params["session"]["workspaceRoot"] = "/tmp/synthetic"
                params["session"]["path"] = "/tmp/synthetic/synthetic-full/session.jsonl"
                params["session"]["activeTurnId"] = None
            if source_sid is None:
                source_sid = params.get("sessionId")
            msg = rekey(msg, tag, source_sid)
            cursor += 1
            if "viewCursor" in msg.get("params", {}):
                msg["params"]["viewCursor"] = f"v:full:{cursor}"
            out.append("<-- " + json.dumps(msg, separators=(",", ":")))
            if stop and msg["method"] == stop:
                break
    header = [
        "# synthetic-full.jsonl — GENERATED by make-full.py from the fixtures it names.",
        "# Never on a wire: notifications only, re-keyed onto one session.",
    ]
    with open(args.out, "w") as f:
        f.write("\n".join(header + out) + "\n")


if __name__ == "__main__":
    main()
